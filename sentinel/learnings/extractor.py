"""Extract learnings from Sentinel assessment findings.

Groups findings by category and root-cause pattern, then produces
Learning objects for groups with 2+ findings (single-instance findings
are repo-specific, not patterns).
"""

from __future__ import annotations

import re
from collections import defaultdict
from datetime import datetime, timezone

from sentinel.learnings.schema import Learning, LearningCategory

# Severity ordering: lower index = higher severity.
_SEVERITY_ORDER = ["Critical", "P1", "P2", "P3"]

# Categories that are always applicable to code generation.
_GENERATION_APPLICABLE_CATEGORIES = {
    "security",
    "concurrency",
    "error_handling",
    "performance",
}

# Minimum group size for automatic generation applicability.
_HIGH_FREQUENCY_THRESHOLD = 3


def _highest_severity(severities: list[str]) -> str:
    """Return the most severe severity from a list."""
    best_idx = len(_SEVERITY_ORDER)
    for sev in severities:
        try:
            idx = _SEVERITY_ORDER.index(sev)
        except ValueError:
            continue
        if idx < best_idx:
            best_idx = idx
    return _SEVERITY_ORDER[best_idx] if best_idx < len(_SEVERITY_ORDER) else severities[0]


def _simplify_description(description: str) -> str:
    """Reduce a finding description to a grouping key.

    Strips trailing location-specific details (file names, function names,
    line numbers) so that findings with the same root cause but different
    locations are grouped together.
    """
    # Remove file path references like "in app.py", "in utils.py:42"
    text = re.sub(r"\bin\s+[\w./:-]+\.(?:py|js|ts|go|rs)\b", "", description)
    # Remove trailing location qualifiers: "in function alpha", "in module X", "in handler B"
    text = re.sub(r"\s+in\s+(?:\w+\s+)*\w+\s*$", "", text)
    # Remove trailing single-letter identifiers (e.g., "handler A" vs "handler B")
    text = re.sub(r"\s+[A-Z]\s*$", "", text)
    # Collapse whitespace
    text = re.sub(r"\s+", " ", text).strip().lower()
    return text


def _map_category(raw_category: str) -> LearningCategory:
    """Map a finding category string to a LearningCategory enum value.

    Falls back to CORRECTNESS for unknown categories.
    """
    try:
        return LearningCategory(raw_category)
    except ValueError:
        return LearningCategory.CORRECTNESS


class LearningExtractor:
    """Extract pattern-level learnings from assessment findings.

    Args:
        findings: List of finding dicts (finding_schema V2 format).
        source_repo: Repository that was reviewed.
        authored_by_foundry: Whether the code was generated by Foundry.
    """

    def __init__(
        self,
        findings: list[dict],
        source_repo: str,
        authored_by_foundry: bool = False,
    ) -> None:
        self._findings = findings
        self._source_repo = source_repo
        self._authored_by_foundry = authored_by_foundry
        self._id_counter = 0

    def extract(self) -> list[Learning]:
        """Extract pattern-level learnings from findings.

        Groups findings by category + root cause pattern. Only extracts
        learnings where 2+ findings share the same pattern.
        """
        if not self._findings:
            return []

        groups = self._group_by_pattern(self._findings)
        learnings: list[Learning] = []

        for (category_str, _pattern_key), group_findings in groups.items():
            if not self._is_pattern_level(group_findings):
                continue

            severities = [f.get("severity", "P3") for f in group_findings]
            severity = _highest_severity(severities)
            finding_ids = [f.get("id", "") for f in group_findings]
            category = _map_category(category_str)
            applicable = self._determine_applicability(
                category_str, severity, len(group_findings),
            )

            # Use the longest description as the pattern text
            descriptions = [f.get("description", "") for f in group_findings]
            pattern_text = max(descriptions, key=len) if descriptions else ""

            learning = Learning(
                id=self._generate_id(),
                source_repo=self._source_repo,
                authored_by_foundry=self._authored_by_foundry,
                category=category,
                severity=severity,
                pattern=pattern_text,
                anti_pattern_code=None,
                correct_pattern_code=None,
                applicable_to_generation=applicable,
                why=f"Found in {len(group_findings)} findings",
                sentinel_finding_ids=finding_ids,
                extracted_at=datetime.now(timezone.utc).isoformat(),
            )
            learnings.append(learning)

        return learnings

    def _group_by_pattern(self, findings: list[dict]) -> dict[tuple[str, str], list[dict]]:
        """Group findings by category + simplified description."""
        groups: dict[tuple[str, str], list[dict]] = defaultdict(list)
        for finding in findings:
            category = finding.get("category", "general")
            description = finding.get("description", "")
            pattern_key = _simplify_description(description)
            groups[(category, pattern_key)].append(finding)
        return groups

    def _is_pattern_level(self, findings_group: list[dict]) -> bool:
        """Determine if a group represents a pattern vs one-off issue."""
        return len(findings_group) >= 2

    def _determine_applicability(
        self, category: str, severity: str, count: int,
    ) -> bool:
        """Determine if learning is applicable to code generation.

        Rules:
        - True: security, concurrency, error_handling, performance patterns
        - True: any pattern seen in 3+ findings
        - False: P3-only severity (cosmetic)
        - False: business logic / requirement mismatches
        """
        # P3 findings are cosmetic — not applicable
        if severity == "P3":
            return False

        # Core categories are always applicable
        if category in _GENERATION_APPLICABLE_CATEGORIES:
            return True

        # High-frequency patterns are applicable regardless of category
        if count >= _HIGH_FREQUENCY_THRESHOLD:
            return True

        return False

    def _generate_id(self) -> str:
        """Generate unique learning ID: LRN-YYYYMMDD-NNN."""
        self._id_counter += 1
        date_str = datetime.now(timezone.utc).strftime("%Y%m%d")
        return f"LRN-{date_str}-{self._id_counter:03d}"
