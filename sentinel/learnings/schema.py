"""Schema for extracted learnings.

Defines the Learning dataclass and LearningCategory enum used by the
extractor, store, and CLI export commands.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum


class LearningCategory(str, Enum):
    """Categories of learnings extracted from assessment findings."""

    SECURITY = "security"
    CONCURRENCY = "concurrency"
    ERROR_HANDLING = "error_handling"
    PERFORMANCE = "performance"
    DATA_INTEGRITY = "data_integrity"
    CORRECTNESS = "correctness"
    MAINTAINABILITY = "maintainability"
    TESTABILITY = "testability"
    CODE_SMELL = "code_smell"


@dataclass
class Learning:
    """A pattern-level learning extracted from assessment findings.

    Attributes:
        id: Unique identifier in LRN-YYYYMMDD-NNN format.
        source_repo: Repository that was reviewed.
        authored_by_foundry: Whether the reviewed code was generated by Foundry.
        category: Classification of the learning.
        severity: Highest severity from contributing findings (Critical, P1, P2, P3).
        pattern: Human-readable description of the anti-pattern.
        anti_pattern_code: Example of bad code (optional).
        correct_pattern_code: Example of correct code (optional).
        applicable_to_generation: Whether Foundry should learn from this.
        why: Explanation of why this matters, including frequency data.
        sentinel_finding_ids: IDs of findings that led to this learning.
        extracted_at: ISO 8601 timestamp of extraction.
    """

    id: str
    source_repo: str
    authored_by_foundry: bool
    category: LearningCategory
    severity: str
    pattern: str
    anti_pattern_code: str | None
    correct_pattern_code: str | None
    applicable_to_generation: bool
    why: str
    sentinel_finding_ids: list[str] = field(default_factory=list)
    extracted_at: str = ""

    def to_dict(self) -> dict:
        """Serialize to a plain dict suitable for JSON persistence."""
        return {
            "id": self.id,
            "source_repo": self.source_repo,
            "authored_by_foundry": self.authored_by_foundry,
            "category": self.category.value if isinstance(self.category, LearningCategory) else self.category,
            "severity": self.severity,
            "pattern": self.pattern,
            "anti_pattern_code": self.anti_pattern_code,
            "correct_pattern_code": self.correct_pattern_code,
            "applicable_to_generation": self.applicable_to_generation,
            "why": self.why,
            "sentinel_finding_ids": list(self.sentinel_finding_ids),
            "extracted_at": self.extracted_at,
        }

    @classmethod
    def from_dict(cls, data: dict) -> Learning:
        """Deserialize from a plain dict."""
        category_value = data["category"]
        if isinstance(category_value, str):
            category = LearningCategory(category_value)
        else:
            category = category_value

        return cls(
            id=data["id"],
            source_repo=data["source_repo"],
            authored_by_foundry=data.get("authored_by_foundry", False),
            category=category,
            severity=data["severity"],
            pattern=data["pattern"],
            anti_pattern_code=data.get("anti_pattern_code"),
            correct_pattern_code=data.get("correct_pattern_code"),
            applicable_to_generation=data.get("applicable_to_generation", False),
            why=data.get("why", ""),
            sentinel_finding_ids=data.get("sentinel_finding_ids", []),
            extracted_at=data.get("extracted_at", ""),
        )

    def validate(self) -> list[str]:
        """Return list of validation errors, empty if valid."""
        errors: list[str] = []
        if not self.id:
            errors.append("id must not be empty")
        if not self.pattern:
            errors.append("pattern must not be empty")
        if not self.source_repo:
            errors.append("source_repo must not be empty")
        if not self.severity:
            errors.append("severity must not be empty")
        if not self.sentinel_finding_ids:
            errors.append("sentinel_finding_ids must not be empty")
        return errors
