"""
sentinel/orchestrator/github_issue_dispatcher.py

Phase A of the GitHub Issues automation — dispatch one Sentinel task to a
GitHub Issue and assign it to the Copilot coding agent, entirely via the ``gh``
CLI (shell-out; no direct HTTP calls, no token management — ``gh`` handles auth
transparently through its keyring credential helper).

The Issue body is the exact same task packet used in the manual Copilot loop
(``task_packet.generate_packet``), so a dispatched Issue carries identical
instructions to what a human pasted into Copilot Chat.
"""
from __future__ import annotations

import logging
import subprocess

from sentinel.orchestrator.state_machine import TaskState
from sentinel.orchestrator.task_packet import generate_packet

log = logging.getLogger(__name__)


class GitHubDispatchError(Exception):
    """Raised when a ``gh`` CLI dispatch operation fails."""


def _require_task_fields(task) -> None:
    """task.plan_id and task.affected_files must be present."""
    if not getattr(task, "plan_id", None):
        raise ValueError("task.plan_id is required for GitHub dispatch")
    if not getattr(task, "affected_files", None):
        raise ValueError("task.affected_files is required for GitHub dispatch")


def _run_gh(args: list[str], what: str) -> subprocess.CompletedProcess:
    """Run a ``gh`` command, translating failures into GitHubDispatchError."""
    try:
        return subprocess.run(
            ["gh", *args],
            check=True,
            capture_output=True,
            encoding="utf-8",
        )
    except FileNotFoundError as exc:
        raise GitHubDispatchError(f"gh CLI not found while {what}: {exc}") from exc
    except subprocess.CalledProcessError as exc:
        raise GitHubDispatchError(
            f"{what} failed (exit {exc.returncode}): {(exc.stderr or '').strip()}"
        ) from exc


def create_issue_for_task(task, repo: str) -> str:
    """Create a GitHub Issue from a task packet. Returns the issue URL.

    Title: ``[Sentinel] {plan_id} — {description[:60]}``. Body is
    ``generate_packet(task)`` verbatim plus an auto-generated scope footer.
    ``gh issue create`` prints the new issue URL to stdout. Raises
    ``GitHubDispatchError`` on gh failure, ``ValueError`` on missing fields.
    """
    _require_task_fields(task)
    title = f"[Sentinel] {task.plan_id} — {task.description[:60]}"
    body = (
        generate_packet(task)
        + "\n\n---\n"
        + "*Auto-generated by Sentinel orchestrator. "
        + f"Scope: {', '.join(task.affected_files)}*\n"
    )
    log.info("Creating GitHub Issue for task %s in %s", task.plan_id, repo)
    result = _run_gh(
        ["issue", "create", "--repo", repo, "--title", title, "--body", body],
        "gh issue create",
    )
    url = (result.stdout or "").strip()
    if not url:
        raise GitHubDispatchError("gh issue create returned no issue URL")
    log.info("Created GitHub Issue: %s", url)
    return url


def assign_to_codex(issue_number: int, repo: str) -> None:
    """Assign the issue to the Copilot coding agent (``@copilot``).

    Raises ``GitHubDispatchError`` on gh failure.
    """
    log.info("Assigning issue #%s in %s to @copilot", issue_number, repo)
    _run_gh(
        ["issue", "edit", str(issue_number), "--repo", repo,
         "--add-assignee", "@copilot"],
        "gh issue edit --add-assignee",
    )
    log.info("Assigned issue #%s to @copilot", issue_number)


def _issue_number_from_url(url: str) -> int:
    """Extract the trailing issue number from a gh issue URL."""
    tail = url.rstrip("/").rsplit("/", 1)[-1]
    try:
        return int(tail)
    except ValueError as exc:
        raise GitHubDispatchError(
            f"Could not parse issue number from URL: {url}"
        ) from exc


def dispatch_task(task, repo: str, state_store) -> str:
    """Full dispatch: create the Issue, assign it to ``@copilot``, set task
    state to ``DISPATCHED_TO_GITHUB``, and persist via ``state_store``. Returns
    the issue URL.

    Atomic with respect to task state: if issue creation (or assignment) raises,
    the task state is NOT updated — no partial state on error.
    """
    _require_task_fields(task)
    # Create first — if this raises, task state is untouched.
    url = create_issue_for_task(task, repo)
    assign_to_codex(_issue_number_from_url(url), repo)
    # Only after both external steps succeed do we record dispatch state.
    task.state = TaskState.DISPATCHED_TO_GITHUB
    state_store.upsert_task(task.to_dict())
    log.info(
        "Task %s dispatched to GitHub: %s (state=%s)",
        task.plan_id, url, task.state.value,
    )
    return url
