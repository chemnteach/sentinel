"""Tests for the Phase-A GitHub Issue dispatcher (gh CLI shell-out, mocked)."""
from __future__ import annotations

import subprocess
from unittest.mock import MagicMock, patch

import pytest

from sentinel.orchestrator.github_issue_dispatcher import (
    GitHubDispatchError,
    assign_to_codex,
    create_issue_for_task,
    dispatch_task,
)
from sentinel.orchestrator.state_machine import TaskState
from sentinel.orchestrator.task_manager import Task

_RUN = "sentinel.orchestrator.github_issue_dispatcher.subprocess.run"
REPO = "chemnteach/sentinel"
ISSUE_URL = "https://github.com/chemnteach/sentinel/issues/42"


def _task(**kw):
    base = dict(
        task_id="t1",
        plan_id="FIX-BLOCKING-002",
        description="Session self-approval default must be inverted for safety",
        affected_files=["sentinel/chat/session.py"],
        acceptance_criteria=["No self-approval by default", "Policy gate required"],
        scope_boundary="session.py only",
    )
    base.update(kw)
    return Task(**base)


def _ok(stdout=""):
    return subprocess.CompletedProcess(args=["gh"], returncode=0, stdout=stdout, stderr="")


def _fail():
    return subprocess.CalledProcessError(returncode=1, cmd=["gh"], stderr="boom")


# --- create_issue_for_task ---

def test_create_issue_calls_gh_with_title_and_full_packet_body():
    with patch(_RUN, return_value=_ok(ISSUE_URL + "\n")) as run:
        create_issue_for_task(_task(), REPO)
    cmd = run.call_args.args[0]
    assert cmd[:3] == ["gh", "issue", "create"]
    assert "--repo" in cmd and REPO in cmd
    title = cmd[cmd.index("--title") + 1]
    assert title.startswith("[Sentinel] FIX-BLOCKING-002 — ")
    body = cmd[cmd.index("--body") + 1]
    # full packet content present, not truncated, + footer
    assert "## Task: FIX-BLOCKING-002" in body
    assert "**Acceptance criteria:**" in body
    assert "1. No self-approval by default" in body
    assert "Hard gates (all required)" in body
    assert "Auto-generated by Sentinel orchestrator" in body
    assert "sentinel/chat/session.py" in body


def test_create_issue_returns_url_from_gh_stdout():
    with patch(_RUN, return_value=_ok(ISSUE_URL + "\n")):
        assert create_issue_for_task(_task(), REPO) == ISSUE_URL


def test_create_issue_raises_on_subprocess_failure():
    with patch(_RUN, side_effect=_fail()):
        with pytest.raises(GitHubDispatchError):
            create_issue_for_task(_task(), REPO)


# --- assign_to_codex ---

def test_assign_calls_gh_with_issue_number_and_copilot():
    with patch(_RUN, return_value=_ok()) as run:
        assign_to_codex(42, REPO)
    cmd = run.call_args.args[0]
    assert cmd[:3] == ["gh", "issue", "edit"]
    assert "42" in cmd
    assert cmd[cmd.index("--add-assignee") + 1] == "@copilot"


def test_assign_raises_on_subprocess_failure():
    with patch(_RUN, side_effect=_fail()):
        with pytest.raises(GitHubDispatchError):
            assign_to_codex(42, REPO)


# --- dispatch_task ---

def test_dispatch_creates_assigns_updates_state_and_persists():
    task = _task()
    store = MagicMock()
    with patch(_RUN, return_value=_ok(ISSUE_URL + "\n")) as run:
        url = dispatch_task(task, REPO, store)
    assert url == ISSUE_URL
    assert run.call_count == 2  # create + assign
    assert task.state == TaskState.DISPATCHED_TO_GITHUB
    store.upsert_task.assert_called_once()
    persisted = store.upsert_task.call_args.args[0]
    assert persisted["state"] == "DISPATCHED_TO_GITHUB"


def test_dispatch_is_atomic_no_state_change_when_create_fails():
    task = _task(state=TaskState.ASSIGNED)
    store = MagicMock()
    with patch(_RUN, side_effect=_fail()):
        with pytest.raises(GitHubDispatchError):
            dispatch_task(task, REPO, store)
    assert task.state == TaskState.ASSIGNED       # unchanged
    store.upsert_task.assert_not_called()          # no partial state
